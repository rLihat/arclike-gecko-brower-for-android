@Composable
private fun StatusCard(title: String, body: String, action: String?, onAction: () -> Unit) {
    val c = LocalArc.current
    Column(
        Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(18.dp))
            .background(c.menuCard)
            .padding(16.dp),
    ) {
        Text(title, color = c.text, fontSize = 15.sp, fontWeight = FontWeight.SemiBold)
        Spacer(Modifier.height(5.dp))
        Text(body, color = c.muted, fontSize = 12.sp, lineHeight = 17.sp)
        if (action != null) {
            Spacer(Modifier.height(8.dp))
            Text(
                action,
                color = c.accent,
                fontSize = 13.sp,
                fontWeight = FontWeight.SemiBold,
                modifier = Modifier
                    .clip(RoundedCornerShape(9.dp))
                    .clickable { onAction() }
                    .padding(horizontal = 6.dp, vertical = 5.dp),
            )
        }
    }
}

@Composable
private fun LoginEditor(
    initial: SavedLogin?,
    onDismiss: () -> Unit,
    onSave: (SavedLogin) -> Unit,
    onGenerate: (Int, Boolean) -> String,
) {
    val c = LocalArc.current
    var host by remember { mutableStateOf(initial?.host ?: "") }
    var username by remember { mutableStateOf(initial?.username ?: "") }
    var password by remember { mutableStateOf(initial?.password ?: "") }
    var show by remember { mutableStateOf(false) }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(if (initial == null) "Add login" else "Edit login") },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                EditorField("Host (e.g. example.com)", host) { host = it }
                EditorField("Username or email", username) { username = it }
                EditorField(
                    "Password",
                    password,
                    visual = if (show) VisualTransformation.None else PasswordVisualTransformation(),
                ) { password = it }
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text(
                        if (show) "Hide" else "Show",
                        color = c.accent,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.SemiBold,
                        modifier = Modifier
                            .clip(RoundedCornerShape(8.dp))
                            .clickable { show = !show }
                            .padding(horizontal = 6.dp, vertical = 4.dp),
                    )
                    Text(
                        "Generate",
                        color = c.accent,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.SemiBold,
                        modifier = Modifier
                            .clip(RoundedCornerShape(8.dp))
                            .clickable { password = onGenerate(18, true) }
                            .padding(horizontal = 6.dp, vertical = 4.dp),
                    )
                }
            }
        },
        confirmButton = {
            TextButton(onClick = {
                if (host.isBlank() || password.isBlank()) return@TextButton
                onSave(
                    SavedLogin(
                        id = initial?.id ?: PasswordStore.newId(),
                        host = host.trim(),
                        username = username.trim(),
                        password = password,
                        updatedAt = System.currentTimeMillis(),
                    )
                )
            }) { Text("Save") }
        },
        dismissButton = { TextButton(onClick = onDismiss) { Text("Cancel") } },
    )
}

@Composable
private fun EditorField(
    label: String,
    value: String,
    visual: VisualTransformation = VisualTransformation.None,
    onChange: (String) -> Unit,
) {
    val c = LocalArc.current
    Column {
        Text(label, color = c.muted, fontSize = 11.sp)
        Spacer(Modifier.height(4.dp))
        BasicTextField(
            value = value,
            onValueChange = onChange,
            singleLine = true,
            visualTransformation = visual,
            textStyle = androidx.compose.ui.text.TextStyle(color = c.text, fontSize = 14.sp),
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(12.dp))
                .background(c.menuCard)
                .padding(horizontal = 12.dp, vertical = 10.dp),
        )
    }
}

