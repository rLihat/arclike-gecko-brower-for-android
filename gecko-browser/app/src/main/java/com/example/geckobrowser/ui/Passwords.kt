private val pwRed = Color(0xFFE0453C)

@Composable
fun PasswordsScreen(vm: BrowserViewModel, onBack: () -> Unit) {
    val c = LocalArc.current
    val version = vm.passwordVersion
    val logins = remember(version, vm.passwordSearch) {
        val q = vm.passwordSearch.trim()
        vm.passwords().filter {
            q.isBlank() || it.host.contains(q, ignoreCase = true) ||
                it.username.contains(q, ignoreCase = true)
        }
    }
    var editing by remember { mutableStateOf<SavedLogin?>(null) }
    var adding by remember { mutableStateOf(false) }
    var deleting by remember { mutableStateOf<SavedLogin?>(null) }
    var showPasswords by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<String?>(null) }

    if (adding || editing != null) {
        LoginEditor(
            initial = editing,
            onDismiss = { adding = false; editing = null },
            onSave = { login ->
                vm.saveLogin(login)
                adding = false; editing = null
            },
            onGenerate = { len, symbols -> vm.generatePassword(len, symbols) },
        )
    }
    deleting?.let { target ->
        AlertDialog(
            onDismissRequest = { deleting = null },
            title = { Text("Delete login?") },
            text = { Text("Remove the saved login for ${target.host}?") },
            confirmButton = {
                TextButton(onClick = { vm.deleteLogin(target.id); deleting = null }) {
                    Text("Delete", color = pwRed)
                }
            },
            dismissButton = { TextButton(onClick = { deleting = null }) { Text("Cancel") } },
        )
    }
    generated?.let { pw ->
        AlertDialog(
            onDismissRequest = { generated = null },
            title = { Text("Generated password") },
            text = {
                Text(pw, fontFamily = FontFamily.Monospace, fontSize = 14.sp)
            },
            confirmButton = {
                TextButton(onClick = { generated = null }) { Text("Done") }
            },
        )
    }

    Column(Modifier.fillMaxSize().background(c.settingsBg)) {
        SettingsHeader(
            title = "Passwords",
            leading = {
                Box(Modifier.size(34.dp).clip(CircleShape).clickable { onBack() },
                    contentAlignment = Alignment.Center) {
                    Glyph(Ico.chevronLeft, c.text, size = 20.dp, strokeWidth = 2.2f)
                }
            },
            icon = { Glyph(Ico.person, c.text, size = 19.dp, strokeWidth = 1.8f) },
        )

        Column(
            Modifier
                .weight(1f)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 16.dp)
                .padding(bottom = 40.dp),
        ) {
            // Autofill service status
            Spacer(Modifier.height(10.dp))
            StatusCard(
                title = if (vm.isAutofillServiceActive()) "Autofill is on"
                else "Autofill is off",
                body = if (vm.isAutofillServiceActive())
                    "horiZen fills saved logins into login forms on websites and in other apps."
                else
                    "Select horiZen as your device's autofill service to fill saved logins into forms.",
                action = if (vm.isAutofillServiceActive()) null else "Open autofill settings",
                onAction = { vm.openAutofillSettings() },
            )

            SectionLabel("Autofill")
            SettingsGroup {
                SettingsRow(
                    "Autofill logins",
                    icon = { Glyph(Ico.person, c.text, size = 20.dp, strokeWidth = 1.8f) },
                    trailing = { ArcSwitch(vm.isAutofillEnabled()) { vm.setAutofillEnabled(it) } },
                    onClick = { vm.setAutofillEnabled(!vm.isAutofillEnabled()) },
                )
                SettingsRow(
                    "Offer to save logins",
                    icon = { Glyph(Ico.link, c.text, size = 20.dp, strokeWidth = 1.8f) },
                    trailing = { ArcSwitch(vm.isOfferToSave()) { vm.setOfferToSave(it) } },
                    onClick = { vm.setOfferToSave(!vm.isOfferToSave()) },
                )
            }

            SectionLabel("Saved logins (${logins.size})")
            // search
            Row(
                Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(14.dp))
                    .background(c.menuCard)
                    .padding(horizontal = 12.dp, vertical = 4.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Glyph(Ico.find, c.muted, size = 16.dp, strokeWidth = 2f)
                Spacer(Modifier.width(8.dp))
                Box(Modifier.weight(1f)) {
                    if (vm.passwordSearch.isBlank()) {
                        Text("Search logins", color = c.muted, fontSize = 13.sp)
                    }
                    BasicTextField(
                        value = vm.passwordSearch,
                        onValueChange = { vm.onPasswordSearchChange(it) },
                        singleLine = true,
                        textStyle = androidx.compose.ui.text.TextStyle(color = c.text, fontSize = 13.sp),
                        modifier = Modifier.fillMaxWidth(),
                    )
                }
            }
            Spacer(Modifier.height(8.dp))

            if (logins.isEmpty()) {
                Box(
                    Modifier
                        .fillMaxWidth()
                        .clip(RoundedCornerShape(18.dp))
                        .background(c.menuCard)
                        .padding(22.dp),
                    contentAlignment = Alignment.Center,
                ) {
                    Text("No saved logins yet", color = c.muted, fontSize = 13.sp)
                }
            } else {
                Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    logins.forEach { login ->
                        LoginRow(
                            login = login,
                            showPassword = showPasswords,
                            onRevealToggle = { showPasswords = !showPasswords },
                            onEdit = { editing = login },
                            onDelete = { deleting = login },
                            onCopyUser = { vm.copyPasswordToClipboard(login.username) },
                            onCopyPass = { vm.copyPasswordToClipboard(login.password) },
                        )
                    }
                }
            }

            Spacer(Modifier.height(14.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                ActionChip("Add login") { adding = true }
                ActionChip("Generate password") { generated = vm.generatePassword(18, true) }
            }

            Text(
                "Passwords are encrypted with a key stored in this device's Keystore. " +
                    "They are not synced and cannot be recovered if the app is uninstalled.",
                color = c.muted,
                fontSize = 11.sp,
                lineHeight = 15.sp,
                modifier = Modifier.padding(start = 4.dp, top = 18.dp, end = 4.dp),
            )
        }
    }
}

@Composable
private fun LoginRow(
    login: SavedLogin,
    showPassword: Boolean,
    onRevealToggle: () -> Unit,
    onEdit: () -> Unit,
    onDelete: () -> Unit,
    onCopyUser: () -> Unit,
    onCopyPass: () -> Unit,
) {
    val c = LocalArc.current
    Column(
        Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(18.dp))
            .background(c.menuCard)
            .padding(14.dp),
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Column(Modifier.weight(1f)) {
                Text(login.host, color = c.text, fontSize = 14.sp, fontWeight = FontWeight.SemiBold)
                Text(login.username, color = c.muted, fontSize = 12.sp)
            }
            Text(
                if (showPassword) "Hide" else "Show",
                color = c.accent,
                fontSize = 12.sp,
                fontWeight = FontWeight.SemiBold,
                modifier = Modifier
                    .clip(RoundedCornerShape(8.dp))
                    .clickable { onRevealToggle() }
                    .padding(horizontal = 6.dp, vertical = 4.dp),
            )
        }
        Spacer(Modifier.height(6.dp))
        Text(
            if (showPassword) login.password else "•".repeat(login.password.length.coerceAtMost(16)),
            color = c.text,
            fontSize = 13.sp,
            fontFamily = FontFamily.Monospace,
        )
        Spacer(Modifier.height(8.dp))
        Row(horizontalArrangement = Arrangement.spacedBy(14.dp)) {
            SmallAction("Copy user", onCopyUser)
            SmallAction("Copy pass", onCopyPass)
            SmallAction("Edit", onEdit)
            SmallAction("Delete", onDelete)
        }
    }
}

